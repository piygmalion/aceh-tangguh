/**
 * Regenerates src/components/beranda/peta-teaser-paths.ts from
 * public/fixtures/boundaries-aceh-kab.geojson.
 *
 * Web Mercator, fitted to the viewBox with 4% padding.
 * Douglas–Peucker on each open ring (epsilon 0.85 viewBox units), then closed.
 * Rings whose bbox is under 2.2 viewBox units are omitted.
 *
 * Usage: node scripts/build-peta-teaser-paths.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = join(root, "public/fixtures/boundaries-aceh-kab.geojson");
const target = join(root, "src/components/beranda/peta-teaser-paths.ts");
const WIDTH = 691;
const HEIGHT = 860;
const PAD = 0.04;
const EPSILON = 0.85;
const MIN_BBOX = 2.2;

function mercator(lon, lat) {
  const x = (lon * Math.PI) / 180;
  const y = Math.log(Math.tan(Math.PI / 4 + (lat * Math.PI) / 360));
  return [x, y];
}

function perpendicular(point, start, end) {
  const dx = end[0] - start[0];
  const dy = end[1] - start[1];
  const len = Math.hypot(dx, dy);
  if (len === 0) return Math.hypot(point[0] - start[0], point[1] - start[1]);
  return Math.abs(dy * point[0] - dx * point[1] + end[0] * start[1] - end[1] * start[0]) / len;
}

function simplify(points, epsilon) {
  if (points.length < 3) return points;
  let max = 0;
  let index = 0;
  const last = points.length - 1;
  for (let i = 1; i < last; i += 1) {
    const distance = perpendicular(points[i], points[0], points[last]);
    if (distance > max) {
      max = distance;
      index = i;
    }
  }
  if (max > epsilon) {
    const left = simplify(points.slice(0, index + 1), epsilon);
    const right = simplify(points.slice(index), epsilon);
    return left.slice(0, -1).concat(right);
  }
  return [points[0], points[last]];
}

function ringBBox(ring) {
  let minX = Infinity;
  let minY = Infinity;
  let maxX = -Infinity;
  let maxY = -Infinity;
  for (const [x, y] of ring) {
    minX = Math.min(minX, x);
    minY = Math.min(minY, y);
    maxX = Math.max(maxX, x);
    maxY = Math.max(maxY, y);
  }
  return { minX, minY, maxX, maxY, width: maxX - minX, height: maxY - minY };
}

const collection = JSON.parse(readFileSync(source, "utf8"));
const projected = collection.features.map((feature) => ({
  kode_kab: String(feature.properties.kode_kab),
  name: String(feature.properties.name),
  polygons: feature.geometry.coordinates.map((polygon) =>
    polygon.map((ring) => ring.map(([lon, lat]) => mercator(lon, lat))),
  ),
}));

let minX = Infinity;
let minY = Infinity;
let maxX = -Infinity;
let maxY = -Infinity;
for (const feature of projected) {
  for (const polygon of feature.polygons) {
    for (const ring of polygon) {
      for (const [x, y] of ring) {
        minX = Math.min(minX, x);
        minY = Math.min(minY, y);
        maxX = Math.max(maxX, x);
        maxY = Math.max(maxY, y);
      }
    }
  }
}
const spanX = maxX - minX;
const spanY = maxY - minY;
const x0 = minX - spanX * PAD;
const y0 = minY - spanY * PAD;
const x1 = maxX + spanX * PAD;
const y1 = maxY + spanY * PAD;
const scaleX = WIDTH / (x1 - x0);
const scaleY = HEIGHT / (y1 - y0);

function toView(point) {
  const x = (point[0] - x0) * scaleX;
  const y = (y1 - point[1]) * scaleY;
  return [Math.round(x * 10) / 10, Math.round(y * 10) / 10];
}

const paths = projected.map((feature) => {
  const parts = [];
  for (const polygon of feature.polygons) {
    for (const ring of polygon) {
      const open = ring.slice(0, -1);
      if (open.length < 3) continue;
      const simplified = simplify(open.map(toView), EPSILON);
      if (simplified.length < 3) continue;
      const box = ringBBox(simplified);
      if (box.width < MIN_BBOX && box.height < MIN_BBOX) continue;
      const head = simplified[0];
      const rest = simplified.slice(1).map(([x, y]) => `L${x.toFixed(1)} ${y.toFixed(1)}`);
      parts.push(`M${head[0].toFixed(1)} ${head[1].toFixed(1)}${rest.join("")}Z`);
    }
  }
  return { kode_kab: feature.kode_kab, name: feature.name, d: parts.join("") };
});

const body = paths
  .map(
    (item) => `  {
    "kode_kab": ${JSON.stringify(item.kode_kab)},
    "name": ${JSON.stringify(item.name)},
    "d": ${JSON.stringify(item.d)}
  }`,
  )
  .join(",\n");

const file = `/** Kabupaten outlines for the beranda map teaser.
 * Source geometry: public/fixtures/boundaries-aceh-kab.geojson
 * (23 MultiPolygon features; properties \`name\` and \`kode_kab\`).
 * Projection: Web Mercator, fitted to this viewBox with 4% padding.
 * Simplification: Douglas–Peucker on the open ring, epsilon 0.85 viewBox units, then closed.
 * Rings whose bbox is under 2.2 viewBox units are omitted (sliver noise only).
 * Simeulue, Sabang (Pulau Weh), and Pulau Banyak (Aceh Singkil) remain.
 * Generated by scripts/build-peta-teaser-paths.mjs. Not hand-drawn.
 */
export const PETA_TEASER_VIEWBOX = { width: ${WIDTH}, height: ${HEIGHT} } as const;

export type PetaTeaserPath = {
  readonly kode_kab: string;
  readonly name: string;
  readonly d: string;
};

export const PETA_TEASER_PATHS: readonly PetaTeaserPath[] = [
${body}
];
`;

writeFileSync(target, file);
console.log(`wrote ${paths.length} paths to ${target}`);
